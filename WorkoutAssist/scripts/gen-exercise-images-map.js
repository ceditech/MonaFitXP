#!/usr/bin/env node
/*
 * gen-exercise-images-map.js — scans app/assets/exercises/ and emits a static
 * require() map at app/src/data/exerciseImages.ts.
 *
 * Metro/React Native needs static require() strings, so the map is code-genned.
 * Only files named for a catalog exercise id (ex_001 … ex_020) are mapped —
 * those are the live exercises. Proposed (p1..p15) images may exist on disk but
 * are left unmapped so they don't bloat the bundle until those exercises ship.
 */

const fs = require('fs');
const path = require('path');

const ASSETS_DIR = path.join(__dirname, '..', 'app', 'assets', 'exercises');
const OUT_FILE = path.join(__dirname, '..', 'app', 'src', 'data', 'exerciseImages.ts');

const files = fs.existsSync(ASSETS_DIR) ? fs.readdirSync(ASSETS_DIR) : [];
const mapped = files
  .map(f => ({ f, m: f.match(/^(ex_\d+)\.(jpg|jpeg|png)$/i) }))
  .filter(x => x.m)
  .map(x => ({ id: x.m[1], file: x.f }))
  .sort((a, b) => a.id.localeCompare(b.id));

const entries = mapped
  .map(({ id, file }) => `  '${id}': require('../../assets/exercises/${file}'),`)
  .join('\n');

const out = `// AUTO-GENERATED by scripts/gen-exercise-images-map.js — do not edit by hand.
// Static require() map of Flux-generated exercise hero images, keyed by catalog id.
import { ImageSourcePropType } from 'react-native';

export const EXERCISE_IMAGES: Record<string, ImageSourcePropType> = {
${entries}
};

/** Hero image for an exercise id, or undefined if none was generated. */
export function getExerciseImage(exerciseId?: string): ImageSourcePropType | undefined {
  if (!exerciseId) return undefined;
  return EXERCISE_IMAGES[exerciseId];
}
`;

fs.writeFileSync(OUT_FILE, out);
console.log(`Wrote ${OUT_FILE} with ${mapped.length} mapped images${mapped.length ? ' (' + mapped.map(m => m.id).join(', ') + ')' : ''}.`);
const proposed = files.filter(f => /^p\d+\./i.test(f));
if (proposed.length) console.log(`(${proposed.length} proposed p* images present on disk but left unmapped.)`);
